use frontbox_core::prelude::Hardware;
use frontbox_core::prelude::app_tracer::TraceEvent;
use frontbox_console::protocol::{ClientMessage, FontInfo, ImageInfo, RenderedClip, ServerMessage};
use frontbox_gfx::prelude::{Rgba, named_colors};
use ts_rs::{Config, TS};

fn main() {
  let out = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("web/src/types/generated");
  // JSON has no 64-bit integers; serde_json emits u64 as a plain number
  let cfg = Config::new().with_out_dir(&out).with_large_int("number");

  TraceEvent::export_all(&cfg).unwrap();
  Hardware::export_all(&cfg).unwrap();
  ServerMessage::export_all(&cfg).unwrap();
  ClientMessage::export_all(&cfg).unwrap();
  RenderedClip::export_all(&cfg).unwrap();
  ImageInfo::export_all(&cfg).unwrap();
  FontInfo::export_all(&cfg).unwrap();
  export_named_colors(&out);
}

/// ts-rs only exports types, and these are values
fn export_named_colors(out: &std::path::Path) {
  let colors: String = named_colors()
    .into_iter()
    .map(|(name, Rgba([r, g, b, _]))| format!("  {{ name: '{name}', hex: '#{r:02x}{g:02x}{b:02x}' }},\n"))
    .collect();
  let source = format!(
    "// Generated by the export_types example from frontbox-gfx's named_colors. Do not edit this file manually.\n\nexport const NAMED_COLORS = [\n{colors}]\n"
  );
  std::fs::write(out.join("namedColors.ts"), source).unwrap();
}
